def build_main_text() -> str:
    """Собрать текст главного экрана FAQ.

    Внизу — подпись с названием и версией бота, поэтому раздел FAQ
    всегда показывает актуальную версию (:data:`config.BOT_VERSION`).
    """
    return (
        f"{FAQ_TITLE}\n\n"
        f"{FAQ_INTRO}\n\n"
        "━━━━━━━━━━━━━\n"
        f"{config.BOT_NAME} v{config.BOT_VERSION}"
    )


def section_title(section_id: str) -> str:
    """Подпись кнопки раздела или пустая строка, если раздела нет."""
    for known_id, title in FAQ_SECTIONS:
        if known_id == section_id:
            return title
    return ""

